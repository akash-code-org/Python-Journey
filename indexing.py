s = 'Hello coder' 
print(s[0]) # eys ko positive indexing kehte he, keo ki index 0 se start hota he


print(s[-5]) # Negative indexing matlb string ke end se values ko print krna, jo -1 se start hoti he
# opposite of positive indexing


# Slicing -> mtlb string ka koi spesific part access krna indexs
print(s[0:5])


# Ulta access krna
print(s[6:0:-1])


# Ulta print 2 ke jump se
print(s[7:0:-2])


# String ka reverse
print(s[::-1])